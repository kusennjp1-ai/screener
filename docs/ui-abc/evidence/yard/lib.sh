#!/bin/bash
# SCRATCH (ui-abc yardstick, never committed): shared settings of the yard's browser tools. CI-faithful through the round-3
# harness's lib/common.sh (Chrome for Testing 147 headless shell, the CI fonts, Node 22). Source it, then
# `yard_run_dir <kind> <worktree> <port> <spec>` prints a per-run Playwright dir whose config serves the worktree's own
# frontend (its playwright.static.config.js vite dev server, --strictPort) on <port>, with reduced motion and the spec's
# helper modules copied beside it.
source $SCRATCH/audit3/r3-harness/lib/common.sh
export Y=$S/ui-abc/yard
yard_run_dir() {
  local kind=$1 W=$2 PORT=$3 SPEC=$4 RUN=$Y/runs/$1-$3
  rm -rf "$RUN"; mkdir -p "$RUN"
  cp "$Y/$SPEC" "$Y/states.mjs" "$Y/extract.mjs" "$RUN"/
  ln -s "$(readlink -f "$W/frontend/node_modules")" "$RUN/node_modules"
  echo '{"type":"module"}' > "$RUN/package.json"
  cat > "$RUN/pw.config.mjs" <<CFG
// SCRATCH yard config (generated by lib.sh): worktree $W, port $PORT, spec $SPEC.
import base from '$W/frontend/playwright.static.config.js';
const PORT = $PORT;
export default { ...base, testDir: '$RUN', testMatch: /$(basename "$SPEC" | sed 's/\./\\./g')\$/, outputDir: '$RUN/test-results', reporter: 'line', workers: 1, retries: 0, timeout: 180000,
  use: { ...base.use, baseURL: 'http://127.0.0.1:' + PORT, trace: 'off', contextOptions: { reducedMotion: 'reduce' }, launchOptions: { executablePath: '$CFT' } },
  webServer: { ...base.webServer, command: 'npm run dev -- --host 127.0.0.1 --port ' + PORT + ' --strictPort', url: 'http://127.0.0.1:' + PORT, cwd: '$W/frontend', reuseExistingServer: false } };
CFG
  echo "$RUN"
}
# The ports this workflow may use: 4461 (the S1 worktree, or a throwaway tree when S1 is not served) and 4462 (main).
yard_port_ok() { case "$1" in 4461|4462) return 0;; *) echo "port $1 is not 4461/4462" >&2; return 1;; esac; }
